#!/bin/sh

set -e

# Passport-ийн түлхүүрүүд ачаалагдаж байгааг ХАМГИЙН ТҮРҮҮНД шалгана.
#
# Яагаад эхэнд вэ:
#   1. Энэ шалгалт өгөгдлийн сан шаардахгүй бөгөөд агшин зуур дуусна.
#      Хамгийн хямд, хамгийн магадлалтай шалгалтыг эхэнд тавина.
#   2. Доорх `until` давталт нь ХЯЗГААРГҮЙ. Сан холбогдохгүй бол түүний
#      ДАРАА тавьсан ямар ч шалгалт хэзээ ч ажиллахгүй — Cloud Run зөвхөн
#      "container failed to start" гэж хэлээд түлхүүрийн талаар дуугарахгүй.
#
# set -e идэвхтэй тул амжилтгүй бол контейнер ЭНД зогсоно. Cloud Run тухайн
# хувилбарыг татгалзаж, өмнөх ажиллаж байгаа хувилбараа үргэлжлүүлэн үйлчилнэ.
echo "==> Passport-ийн түлхүүрүүдийг шалгаж байна..."
php artisan keys:verify

echo "==> Өгөгдлийн сан бэлэн болохыг хүлээж байна..."
until php artisan db:show > /dev/null 2>&1; do
    echo "    ...хүлээж байна"
    sleep 2
done
echo "==> Өгөгдлийн сан бэлэн боллоо."

php artisan config:clear
php artisan route:clear
php artisan migrate --force --isolated
php artisan cache:clear

echo "==> Ажиллуулж байна: $*"
exec "$@"
